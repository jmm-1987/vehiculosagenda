def esc(s: str) -> str:
    return s.replace("'", "''")


def main():
    rows = []
    for i, line in enumerate(CSV.strip().splitlines()):
        if i == 0:
            continue
        parts = line.split(";", 3)
        if len(parts) < 3:
            continue
        emp, fecha, causa = parts[0].strip(), parts[1].strip(), parts[2].strip().upper()
        nota = parts[3].strip() if len(parts) > 3 else ""
        d, m, y = fecha.split("/")
        rows.append((emp, f"{y}-{m}-{d}", causa, nota))

    emps = sorted({r[0] for r in rows})
    out = Path(__file__).with_name("import_vacaciones_ausencias_merida_2026.sql")

    lines = [
        "-- Import ausencias vacaciones Merida 2026",
        "-- DB SQLite: database/VEHICULOS.db",
        "--",
        "-- PASO A (solo la primera vez, si falla 'duplicate column' ignoralo):",
        "--   ALTER TABLE vacaciones_ausencia ADD COLUMN nota VARCHAR(1000) DEFAULT '';",
        "--",
        "-- PASO B:",
        "--   sqlite3 /ruta/database/VEHICULOS.db < vacaciones/import_vacaciones_ausencias_merida_2026.sql",
        "--",
        "-- Reejecutable: UPSERT por (empleado_id, fecha). Sede = merida.",
        "",
        "BEGIN;",
        "",
        "CREATE UNIQUE INDEX IF NOT EXISTS uq_vacaciones_ausencia_emp_fecha",
        "  ON vacaciones_ausencia(empleado_id, fecha);",
        "",
    ]

    for emp, iso, causa, nota in rows:
        lines.extend(
            [
                "INSERT INTO vacaciones_ausencia",
                "  (empleado_id, fecha, codigo, nota, adjunto, adjunto_nombre, usuario, fecha_registro)",
                f"SELECT e.id, '{iso}', '{causa}', '{esc(nota)}', '', '', 'import', datetime('now')",
                "FROM vacaciones_empleado e",
                f"WHERE e.sede = 'merida' AND e.nombre = '{esc(emp)}'",
                "ON CONFLICT(empleado_id, fecha) DO UPDATE SET",
                "  codigo = excluded.codigo,",
                "  nota = excluded.nota,",
                "  usuario = excluded.usuario,",
                "  fecha_registro = excluded.fecha_registro;",
                "",
            ]
        )

    lines.append("-- Empleados de la lista no encontrados en plantilla Merida:")
    lines.append("SELECT 'FALTA EMPLEADO: ' || x.nombre AS aviso FROM (")
    for i, e in enumerate(emps):
        if i == 0:
            lines.append(f"  SELECT '{esc(e)}' AS nombre")
        else:
            lines.append(f"  UNION ALL SELECT '{esc(e)}'")
    lines.append(
        ") x WHERE NOT EXISTS ("
        "SELECT 1 FROM vacaciones_empleado e "
        "WHERE e.sede='merida' AND e.nombre=x.nombre);"
    )
    lines.extend(["", "COMMIT;", f"-- Total filas: {len(rows)}", ""])

    out.write_text("\n".join(lines), encoding="utf-8")
    print(f"OK {out.name}: {len(rows)} filas, {len(emps)} empleados")


if __name__ == "__main__":
    main()
